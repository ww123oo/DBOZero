def has_cjk(s: str) -> bool:
    return bool(re.search(r"[\u4e00-\u9fff]", s or ""))


def convert(zh: str) -> str:
    out = zh
    for a, b in REPL:
        if a in out:
            out = out.replace(a, b)
    return out


def main() -> int:
    if not target.exists():
        print("missing", target)
        return 1
    rows = []
    fields = None
    fixed = 0
    with target.open(encoding="utf-8-sig") as f:
        reader = csv.DictReader(f, delimiter="\t")
        fields = reader.fieldnames
        for r in reader:
            loc = (r.get("位置") or "") + (r.get("文件") or "")
            is_lang0 = "lang0" in loc.lower() or (r.get("来源") or "") == "UI"
            zh = (r.get("填写中文") or "").strip()
            if is_lang0 and has_cjk(zh):
                new = convert(zh)
                if new != zh:
                    r["填写中文"] = new
                    fixed += 1
            rows.append(r)
    with target.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"OK: applied lang0/UI S2T fixes to {fixed} rows in data/new_translations.tsv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
